# String Operation in python 

# length of string 
fruit = "Mango"
len1 = len(fruit)
print("Mango is a", len1, "letter word.") 

# String as an Array
pie = "ApplePie"
print(pie[:5]) # Return 0 to 5 between character 
print(pie[6])  # returns character at specified index
print(pie[-8:-3])      # Slicing using negative index

#Loop throught a string 

alphabets = "ABCDE"
